LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.STD_LOGIC_UNSIGNED.ALL;

ENTITY ROM_AFISOR IS
	PORT (ADR_CHAR: IN STD_LOGIC_VECTOR(3 DOWNTO 0); -- VOM AFISA IN HEXA, AVEM NEVOIE DE 4 BITI PT REPREZENTAREA IN BINAR	
	ENABLE:IN STD_LOGIC;
	CHAR:OUT STD_LOGIC_VECTOR(6 DOWNTO 0)); --AVEM 7 SEGMENTE
END ROM_AFISOR;

ARCHITECTURE ARCH_ROM_AFISOR OF ROM_AFISOR IS
TYPE MM IS ARRAY (15 DOWNTO 0) OF STD_LOGIC_VECTOR(6 DOWNTO 0);
SIGNAL HARTA: MM:=("0111000", --F
				   "0110000", --E
				   "1000010", --d
				   "0110001", --C
				   "1100000", --b
				   "0001000", --A
				   "0000100", --9
				   "0000000", --8
				   "0001111", --7
				   "0100000", --6
				   "0100100", --5
				   "1001100", --4
				   "0000110", --3
				   "0010010", --2
				   "1001111", --1
				   "0000001"); --0
				
BEGIN 
	PROCESS(ENABLE)	
	BEGIN
		IF ENABLE='1' THEN
			CHAR<=HARTA(CONV_INTEGER(ADR_CHAR));  
		ELSE 
			CHAR<="1111111";
 		END IF;
	END PROCESS;	 
END ARCH_ROM_AFISOR;	
	