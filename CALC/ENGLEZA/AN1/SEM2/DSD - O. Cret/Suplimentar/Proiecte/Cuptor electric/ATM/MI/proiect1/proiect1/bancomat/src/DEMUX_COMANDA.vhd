LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY DEMUX_COMANDA IS
	PORT(X:IN STD_LOGIC;
		 S:IN STD_LOGIC_VECTOR(2 DOWNTO 0); --SELECTIA ESTE PE 3 BIBI	
	     Y:OUT STD_LOGIC_VECTOR(7 DOWNTO 0 )); --AVEM 8 IESIRI (VOM FOLOSI PRIMELE 6)
END DEMUX_COMANDA;

ARCHITECTURE ARCH_DEMUX_COMANDA OF DEMUX_COMANDA IS
BEGIN
	Y<=('0','0','0','0','0','0','0',X ) WHEN S="000" ELSE 
	   ('0','0','0','0','0','0',X,'0' ) WHEN S="001" ELSE
	   ('0','0','0','0','0',X,'0','0' ) WHEN S="010" ELSE
	   ('0','0','0','0',X,'0','0','0' ) WHEN S="011" ELSE
	   ('0','0','0',X,'0','0','0','0' ) WHEN S="100" ELSE
	   ('0','0',X,'0','0','0','0','0' ) WHEN S="101" ELSE
	   ('0',X,'0','0','0','0','0','0' ) WHEN S="110" ELSE
	   (X,'0','0','0','0','0','0','0' ) WHEN S="111";
END ARCH_DEMUX_COMANDA;	