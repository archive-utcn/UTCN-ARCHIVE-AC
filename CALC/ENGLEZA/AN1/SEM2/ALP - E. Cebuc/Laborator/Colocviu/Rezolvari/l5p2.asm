DATA 	SEGMENT PARA PUBLIC 'DATA'

	NUM1 DB 2
	NUM2 DB 4
	REZ DB ? 
	
DATA 	ENDS

CODE 	SEGMENT PARA PUBLIC 'CODE'

ASSUME CS:CODE, DS:DATA

START	PROC FAR
	
	PUSH DS
	XOR AX,AX
	PUSH AX	 
	MOV AX,DATA
	MOV DS,AX
	
	MOV AL,2
	MOV CL,AL
	MOV BL,3
	MUL NUM1
	MOV DL,AL
	MOV AL,CL
	MUL NUM2
	ADD AL,BL
	ADD DL,AL
	MOV REZ,DL

	RET		
START	ENDP
CODE 	ENDS

	END START
