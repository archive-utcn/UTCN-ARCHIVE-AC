DATA SEGMENT PARA PUBLIC 'DATA'
DATA ENDS

CODE SEGMENT PARA PUBLIC 'CODE'

CONVERT PROC NEAR
	MOV BL, 10
	DIV BL
	XCHG AH, AL
RET
CONVERT ENDP

START PROC FAR
ASSUME CS:CODE, DS:DATA
PUSH DS ;prepare to return to DOS
XOR AX,AX
PUSH AX
MOV AX,DATA; initialise DS
MOV DS, AX

	XOR AH, AH
	MOV AL, 0BH
	CALL CONVERT
	
	XOR AH, AH
	MOV AL, 05H
	CALL CONVERT
	
RET
START ENDP

CODE ENDS

END START

