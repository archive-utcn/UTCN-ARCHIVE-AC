DATA SEGMENT PARA PUBLIC 'DATA'
NUMBERS DB 1,5,2,7,8,11
LENNR DB $-NUMBERS
MESSAGE DB "THIS IS THE AVERAGE OF NUMBERS BETWEEN [5,10]: "
LENMES DW $-MESSAGE
DATA ENDS

CODE SEGMENT PARA PUBLIC 'CODE'
START PROC FAR
ASSUME CS:CODE, DS:DATA
PUSH DS
XOR AX,AX
PUSH AX
MOV AX, DATA
MOV DS, AX

XOR AX, AX
XOR CX, CX
MOV CL, LENNR
MOV LENNR, 0
XOR SI, SI



	L:
	INC SI
	CMP NUMBERS[SI], 5
	JB skip
	CMP NUMBERS[SI], 10
	JA  skip
	
	ADD AL, NUMBERS[SI]		
	INC LENNR
	
	LOOP L
	skip: LOOP L
	

	DIV LENNR
	;XOR AH, AH
	
	;MOV BL, 10
	;DIV BL
	
	MOV SI, LENMES
	MOV MESSAGE[SI], AL
	ADD MESSAGE[SI], '0'
	MOV MESSAGE[SI+1], '.'
	MOV MESSAGE[SI+2], AH
	ADD MESSAGE[SI+2], '0'
	MOV MESSAGE[SI+3], '$'
	
	LEA DX, MESSAGE
	MOV AH, 09H
	INT 21H
	
	RET 
	START ENDP
	
	CODE ENDS
	END START