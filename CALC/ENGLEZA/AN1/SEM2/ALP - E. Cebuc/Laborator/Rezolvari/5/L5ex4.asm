DATA SEGMENT PARA PUBLIC 'DATA'
NUM1 DB 8
NUM2 DB 3
DATA ENDS


CODE SEGMENT PARA PUBLIC 'CODE'
START PROC FAR
ASSUME CS:CODE, DS:DATA
	PUSH DS
	XOR AX,AX
	PUSH AX
	MOV AX, DATA
	MOV DS, AX
	
MOV BL, 8
MOV AL, 3

MOV DL, AL
MOV CL, 3
SHL AL, CL
SUB AL, DL

SHL BL, 1
SUB AL, BL

MOV CL, 4
SHR BL, CL
SUB AL, BL

RET
START ENDP
CODE ENDS
END START

